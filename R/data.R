#' Five Gaussian Cluster Dataset
#'
#' A synthetic 20-dimensional Gaussian cluster dataset generated from
#' multivariate normal distributions. It is used as an example for
#' principal component analysis and differentially private PCA visualization.
#'
#' @details
#' The dataset `gau` contains 1,000 observations in 20 dimensions, with
#' 200 observations in each of five groups, generated with seed 123.
#' For each group \eqn{g = 1, \ldots, 5}, observations are sampled
#' independently from a 20-dimensional multivariate normal distribution
#' \eqn{N_{20}(\mu_g, \Sigma_g)}.
#' The first two groups have covariance matrix \eqn{I_{20}},
#' the third and fourth groups have covariance matrix \eqn{5I_{20}},
#' and the fifth group has covariance matrix \eqn{8I_{20}}.
#' The group mean vectors differ across selected coordinate blocks,
#' producing both separated and partially overlapping cluster structures.
#'
#' @format
#' A data frame with 1,000 observations and 20 numerical variables
#' named `V1`, `V2`, ..., `V20`.
#'
#' @source
#' Generated by the authors of the package.
"gau"


#' Five Gaussian Cluster Dataset with Group Labels
#'
#' A grouped version of [`gau`], with an additional group label column.
#'
#' @details
#' The dataset `gau_g` contains the same 1,000 observations and
#' 20 numerical variables as [`gau`], with 200 observations per group.
#' An additional column, `group`, identifies the five Gaussian clusters.
#' The group labels correspond to the multivariate normal distributions
#' described in [`gau`].
#'
#' @format
#' A data frame with 1,000 observations and 21 variables.
#' The first 20 columns, named `V1`, `V2`, ..., `V20`, are numerical
#' variables identical to those in `gau`.
#' The last column, `group`, is a character variable with values
#' `group1`, `group2`, `group3`, `group4`, and `group5`.
#'
#' @source
#' Generated by the authors of the package.
"gau_g"



