#' Adult numeric data
#'
#' A numerical subset of the Adult dataset from the UCI Machine Learning
#' Repository. The original Adult dataset is based on data extracted from
#' the 1994 United States Census database.
#'
#' This package dataset retains five numerical variables:
#' `age`, `education_num`, `capital_gain`, `capital_loss`, and
#' `hours_per_week`. These selected numerical variables contain no missing
#' values in the original training file, `adult.data`, used here. The
#' resulting dataset contains 32,561 observations; `adult.test` is not included.
#'
#' The variables have substantially different units and scales. For private
#' analyses, any scaling constants must be public and fixed, or estimated
#' privately with their privacy cost accounted for. Scaling by the confidential
#' sample standard deviations is not covered by the package's guarantees.
#'
#' @format A data frame with 32,561 rows and 5 columns:
#' \describe{
#'   \item{age}{Age of the individual.}
#'   \item{education_num}{Ordered education-level code from 1 (Preschool) to
#'     16 (Doctorate), rather than a literal number of years.}
#'   \item{capital_gain}{Capital gain.}
#'   \item{capital_loss}{Capital loss.}
#'   \item{hours_per_week}{Number of working hours per week.}
#' }
#'
#' @source
#' UCI Machine Learning Repository, Adult dataset.
#' The Adult dataset is licensed under the Creative Commons Attribution 4.0
#' International (CC BY 4.0) license.
#'
#' @references
#' \insertRef{adult}{dppca}
#'
"adult"


#' Five Gaussian cluster datasets
#'
#' Synthetic 20-dimensional Gaussian cluster datasets generated from
#' multivariate normal distributions. They are used as examples for principal
#' component analysis and differentially private PCA visualization.
#'
#' @details
#' The dataset `gau` contains 5,000 observations in 20 dimensions, with
#' 1,000 observations in each of five groups, generated with seed 123.
#' The smaller dataset `gau_s` contains 1,000 observations, with 200 per group,
#' generated separately with seed 234 using the same distributional settings.
#' For each group \eqn{g = 1, \ldots, 5}, observations were
#' sampled independently from a 20-dimensional multivariate normal distribution
#' \eqn{N_{20}(\mu_g, \Sigma_g)}. The first two groups have covariance matrix
#' \eqn{I_{20}}, the third and fourth groups have covariance matrix
#' \eqn{5I_{20}}, and the fifth group has covariance matrix \eqn{8I_{20}}.
#' The group mean vectors differ across selected coordinate blocks, producing
#' both separated and partially overlapping cluster structures.
#'
#' @format Data frames with 20 numerical variables named `V1`, `V2`, ...,
#'   `V20`: `gau` has 5,000 rows and `gau_s` has 1,000 rows.
#'
#' @source
#' Generated by the authors of the package.
#'
#' @aliases gau_s
"gau"


#' Five Gaussian cluster datasets with group labels
#'
#' Grouped versions of [`gau`] and `gau_s`, with an additional group label
#' column.
#'
#' @details
#' The dataset `gau_g` contains the same 5,000 observations and 20 numerical
#' variables as [`gau`], with 1,000 observations per group. The dataset
#' `gau_s_g` contains the same 1,000 observations as `gau_s`, with 200 per group.
#' Both datasets add a label column identifying the five groups.
#'
#' @format Data frames with 21 columns: `gau_g` has 5,000 rows and `gau_s_g`
#' has 1,000 rows. The first 20 columns, named `V1`, `V2`, ..., `V20`, are the
#' numerical variables from `gau` or `gau_s`, respectively.
#' The last column, `group`, is a character group label with values `group1`,
#' `group2`, `group3`, `group4`, and `group5`.
#'
#' @source
#' Generated by the authors of the package.
#'
#' @aliases gau_s_g
"gau_g"
